// The progress docs' conflicts.

/// Which side of a conflict hunk is the PR's. In a rebase "ours" is the base being rebased onto
/// (`main`, or the PR below) and "theirs" the PR's commit being replayed; merging the base into
/// the PR's branch, it is the other way round.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MrSide {
    /// A rebase.
    Theirs,
    /// The base merged into the PR's branch.
    Ours,
}

/// One conflict hunk: the lines of each side, line endings kept.
struct Hunk<'a> {
    ours: Vec<&'a str>,
    theirs: Vec<&'a str>,
    /// 1-based line of its `<<<<<<<` marker.
    line: usize,
}

fn is_marker(line: &str, marker: &str) -> bool {
    let l = line.trim_end_matches(['\r', '\n']);
    l == marker || l.strip_prefix(marker).is_some_and(|r| r.starts_with(' '))
}

/// A revision row: `| YYYY-MM-DD | …`.
pub fn is_row(line: &str) -> bool {
    let b = line.as_bytes();
    line.starts_with("| ")
        && b.len() > 13
        && b.get(2..12).is_some_and(|d| d.iter().enumerate().all(|(i, c)| if i == 4 || i == 7 { *c == b'-' } else { c.is_ascii_digit() }))
        && line.get(12..14) == Some(" |")
}

/// Resolve every conflict in a progress doc at `path`: header lines take the PR's change note
/// (the later of each date), revision rows are the PR's then the base's (each once), and the
/// table then keeps [`KEEP_ROWS`] rows. Any other hunk is refused, naming its line. `side` says
/// which side of each hunk is the PR's.
pub fn resolve_progress(path: &str, text: &str, side: MrSide) -> Result<String, String> {
    let mut out = String::with_capacity(text.len());
    let mut lines = text.split_inclusive('\n').enumerate();
    let mut in_revisions = false;
    let mut hunks = 0usize;
    while let Some((i, line)) = lines.next() {
        if !is_marker(line, "<<<<<<<") {
            in_revisions |= line.trim_end() == REVISIONS;
            out.push_str(line);
            continue;
        }
        let hunk = read_hunk(&mut lines, i + 1).ok_or_else(|| format!("{path}: the conflict at line {} never ends", i + 1))?;
        hunks += 1;
        out.push_str(&resolve_hunk(&hunk, in_revisions, side).map_err(|why| format!("{path}: the conflict at line {}: {why}", hunk.line))?);
    }
    if hunks == 0 {
        return Err(format!("{path}: git says it conflicts, but it has no conflict markers"));
    }
    Ok(trim_rows(path, &out))
}

fn read_hunk<'a>(lines: &mut impl Iterator<Item = (usize, &'a str)>, line: usize) -> Option<Hunk<'a>> {
    let (mut ours, mut theirs) = (Vec::new(), Vec::new());
    // 0: ours, 1: the diff3 base (dropped), 2: theirs.
    let mut side = 0;
    for (_, l) in lines.by_ref() {
        if side == 0 && is_marker(l, "|||||||") {
            side = 1;
        } else if side < 2 && is_marker(l, "=======") {
            side = 2;
        } else if side == 2 && is_marker(l, ">>>>>>>") {
            return Some(Hunk { ours, theirs, line });
        } else if side == 0 {
            ours.push(l);
        } else if side == 2 {
            theirs.push(l);
        }
    }
    None
}

fn resolve_hunk(h: &Hunk<'_>, in_revisions: bool, side: MrSide) -> Result<String, String> {
    let (base, mr) = match side {
        MrSide::Theirs => (&h.ours, &h.theirs),
        MrSide::Ours => (&h.theirs, &h.ours),
    };
    let header = |lines: &[&str]| matches!(lines, [l] if l.starts_with(HEADER));
    if header(base) && header(mr) {
        let (Some(b), Some(m)) = (base.first(), mr.first()) else { return Err("an empty header".into()) };
        return Ok(merge_header(b, m));
    }
    let rows = |lines: &[&str]| lines.iter().all(|l| is_row(l));
    if in_revisions && rows(base) && rows(mr) {
        let mut seen: Vec<&str> = Vec::new();
        for l in mr.iter().chain(base.iter()) {
            if !seen.iter().any(|s| s.trim_end() == l.trim_end()) {
                seen.push(l);
            }
        }
        return Ok(seen.concat());
    }
    Err("not a header or revision rows: resolve it by hand".into())
}

/// The header's `**Key:** value` parts, in order.
fn header_parts(line: &str) -> Vec<(String, String)> {
    let body = line.trim_end().strip_prefix("> ").unwrap_or(line.trim_end());
    body.split(" · ")
        .map(|part| match part.strip_prefix("**").and_then(|p| p.split_once(":**")) {
            Some((k, v)) => (k.to_owned(), v.trim().to_owned()),
            None => (String::new(), part.to_owned()),
        })
        .collect()
}

/// The base's header line with the PR's change note and the later of each date; the base's line
/// ending.
pub fn merge_header(base: &str, mr: &str) -> String {
    let mr_parts = header_parts(mr);
    let mr_of = |k: &str| mr_parts.iter().find(|(key, _)| key == k).map(|(_, v)| v.clone());
    let parts: Vec<String> = header_parts(base)
        .into_iter()
        .map(|(k, v)| {
            let v = match k.as_str() {
                "Change" => mr_of(&k).unwrap_or(v),
                // ISO dates: the later sorts last.
                "Last reviewed" | "Last updated" => mr_of(&k).filter(|t| *t > v).unwrap_or(v),
                _ => v,
            };
            if k.is_empty() { v } else { format!("**{k}:** {v}") }
        })
        .collect();
    let ending = if base.ends_with("\r\n") {
        "\r\n"
    } else if base.ends_with('\n') {
        "\n"
    } else {
        ""
    };
    format!("> {}{ending}", parts.join(" · "))
}

/// Keep the first [`KEEP_ROWS`] revision rows, and point at git for the rest.
fn trim_rows(path: &str, text: &str) -> String {
    let Some(at) = text.find(REVISIONS) else { return text.to_owned() };
    let (head, tail) = text.split_at(at);
    let mut rows = 0usize;
    let mut kept = String::with_capacity(tail.len());
    for line in tail.split_inclusive('\n') {
        if is_row(line) {
            rows += 1;
            if rows > KEEP_ROWS {
                continue;
            }
        }
        kept.push_str(line);
    }
    if rows > KEEP_ROWS && !kept.contains("Older rows") {
        kept = format!("{}\n\nOlder rows: `git log -p {path}`.\n", kept.trim_end_matches(['\n', '\r']));
    }
    format!("{head}{kept}")
}

