/// One stacked PR, as `land` needs it.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Entry {
    pub mr: u64,
    pub source_branch: String,
    pub title: String,
    pub issues: Vec<u64>,
    /// The source branch's tip before the rebase: `land` pushes over nothing else.
    pub old_tip: String,
    /// The rebased tip, `s-<pr>`'s when stacked.
    pub new_tip: String,
    /// What it was stacked onto: `<remote>/<base>`'s tip, or the rebased tip of the PR below. A
    /// branch a worker moved since is restacked onto it to compare trees;
    /// empty in a record from before.
    pub onto: String,
    /// Every file it changes is Markdown, so `main`'s workflows skip its merge.
    pub docs_only: bool,
    /// It carries merge commits, so its base was merged in rather than rebased onto: `land`
    /// merges `main` in again rather than asking the server to rebase it.
    pub merged_base: bool,
    /// The generated docs that conflicted and were regenerated on its stacked tree, in one commit
    /// on top of it: `land` pushes that commit with the PR.
    pub regenerated: Vec<String>,
}

impl Entry {
    fn to_json(&self) -> Value {
        json!({
            "mr": self.mr,
            "source_branch": self.source_branch,
            "title": self.title,
            "issues": self.issues,
            "old_tip": self.old_tip,
            "new_tip": self.new_tip,
            "onto": self.onto,
            "docs_only": self.docs_only,
            "merged_base": self.merged_base,
            "regenerated": self.regenerated,
        })
    }

    /// An entry as [`Entry::to_json`] wrote it (or either consumer's xtask before the move): the
    /// fields added later default when missing.
    fn from_json(v: &Value) -> Result<Self, String> {
        let text = |k: &str| v.get(k).and_then(Value::as_str).map(str::to_owned).ok_or_else(|| format!("an entry has no `{k}`"));
        let list = |k: &str| v.get(k).and_then(Value::as_array).cloned().unwrap_or_default();
        Ok(Entry {
            mr: v.get("mr").and_then(Value::as_u64).ok_or("an entry has no `mr`")?,
            source_branch: text("source_branch")?,
            title: text("title")?,
            issues: list("issues").iter().filter_map(Value::as_u64).collect(),
            old_tip: text("old_tip")?,
            new_tip: text("new_tip")?,
            onto: text("onto").unwrap_or_default(),
            docs_only: v.get("docs_only").and_then(Value::as_bool).ok_or("an entry has no `docs_only`")?,
            merged_base: v.get("merged_base").and_then(Value::as_bool).unwrap_or(false),
            regenerated: list("regenerated").iter().filter_map(|r| r.as_str().map(str::to_owned)).collect(),
        })
    }
}

/// The stack this worktree last made: what `land` lands.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Stack {
    pub remote: String,
    pub base: String,
    pub entries: Vec<Entry>,
}

impl Stack {
    /// The record as JSON (the shape both consumers' xtask wrote before the move).
    pub fn to_json(&self) -> Value {
        json!({"remote": self.remote, "base": self.base, "entries": self.entries.iter().map(Entry::to_json).collect::<Vec<_>>()})
    }

    /// A record [`Stack::to_json`] wrote.
    pub fn from_json(v: &Value) -> Result<Self, String> {
        let text = |k: &str| v.get(k).and_then(Value::as_str).map(str::to_owned).ok_or_else(|| format!("the stack has no `{k}`"));
        let entries = v.get("entries").and_then(Value::as_array).ok_or("the stack has no `entries`")?;
        Ok(Stack { remote: text("remote")?, base: text("base")?, entries: entries.iter().map(Entry::from_json).collect::<Result<_, _>>()? })
    }
}

/// A commit id as people read it: its first 7 characters.
pub fn short(id: &str) -> &str {
    id.get(..7).unwrap_or(id)
}

/// The local branch a PR is stacked on.
pub fn local_branch(mr: u64) -> String {
    format!("s-{mr}")
}

/// A branch name safe to hand to git and to a GitHub API path: letters, digits, `-`, `_`, `.`,
/// `/`; never an option, a range, a path climb or a lock file.
pub fn valid_branch(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 200
        && !name.starts_with(['-', '.', '/'])
        && !name.ends_with(['/', '.'])
        && !name.ends_with(".lock")
        && !name.contains("..")
        && !name.contains("//")
        && name.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.' | '/'))
}

/// The issues `description` closes with GitHub's closing words (`Closes #171`), in order, once
/// each. HTML comments (the PR template's guidance) don't count.
pub fn closed_issues(description: &str) -> Vec<u64> {
    let text = strip_comments(description);
    let mut found = Vec::new();
    let mut rest = text.as_str();
    while let Some(at) = rest.find('#') {
        let digits: String = rest.get(at + 1..).unwrap_or_default().chars().take_while(char::is_ascii_digit).collect();
        if let Ok(n) = digits.parse::<u64>()
            && !found.contains(&n)
            && claim::closes(&text, n)
        {
            found.push(n);
        }
        rest = rest.get(at + 1..).unwrap_or_default();
    }
    found
}

/// `text` without its `<!-- … -->` comments (an unclosed one runs to the end).
fn strip_comments(text: &str) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some(at) = rest.find("<!--") {
        out.push_str(rest.get(..at).unwrap_or_default());
        rest = rest.get(at..).and_then(|r| r.find("-->").and_then(|end| r.get(end + 3..))).unwrap_or_default();
    }
    out.push_str(rest);
    out
}

/// A change is docs-only when every file it touches is Markdown: its merge skips `main`'s
/// workflows (`[skip ci]`; docs/swarm-protocol.md › The coordinator's loop). Stricter than a docs gate (no
/// crate built): a `scorecard/*.toml` or `.github/workflows/` change may get the docs gate locally,
/// but `main`'s workflows still run. An empty change is not docs-only.
pub fn docs_only(files: &[String]) -> bool {
    !files.is_empty() && files.iter().all(|f| f.to_ascii_lowercase().ends_with(".md"))
}

/// One PR in [`crate::github`]'s shape, checked: open, ready, from this repository, with a safe
/// branch.
pub fn parse_mr(project: &Project, v: &Value) -> Result<StackMr, String> {
    let iid = v.get("number").and_then(Value::as_u64).ok_or("GitHub's answer has no number")?;
    let text = |k: &str| v.get(k).and_then(Value::as_str).unwrap_or_default().to_owned();
    let state = text("state");
    if state != "open" {
        return Err(format!("#{iid} is {state}, not open"));
    }
    if v.get("draft").and_then(Value::as_bool).unwrap_or(false) {
        return Err(format!("#{iid} is a draft: only ready PRs are stacked"));
    }
    if v.get("cross_repo").and_then(Value::as_bool).unwrap_or(false) {
        return Err(format!("#{iid} comes from another repository (a fork): not stacked"));
    }
    let source_branch = text("head_ref");
    if !valid_branch(&source_branch) || source_branch == project.branches.main {
        return Err(format!("#{iid}: head branch `{source_branch}` is not one to stack"));
    }
    Ok(StackMr { iid, source_branch, title: text("title"), issues: closed_issues(&text("body")) })
}

