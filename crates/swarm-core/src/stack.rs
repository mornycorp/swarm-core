//! `cargo xtask stack <pr>…`: the coordinator stacks ready PRs for
//! one gate.
//!
//! In the coordinator's gate worktree, for each PR in order: `checkout -B s-<m>` at its source
//! branch, then rebase it onto `origin/main`, or onto the PR before it in the stack (`--onto` that
//! PR's rebased branch, from its old tip when this PR was stacked on it). HEAD ends at the top of
//! the stack, which `cargo xtask gate` then checks.
//!
//! - **A branch that carries merge commits is merged, not rebased** (ns: the coordinator's
//!   `merge.py` did so): a rebase replays commit by commit and loses the conflict resolutions the
//!   merges hold, so its base (`origin/main`, or the PR below) is merged into it instead
//!   ([`Entry::merged_base`]).
//! - **Each branch's pre-rebase tip is recorded** (with the rest of the stack, in the worktree's
//!   git dir: [`Project::stack_state`]). `cargo xtask land` refuses to push over a branch that moved
//!   since, so a worker's newer commits are never overwritten.
//! - **Conflicts in the progress docs' headers and revision tables are resolved** (what the
//!   coordinators' scripts did by hand): the header takes the PR's change note (and the later of
//!   each date), the revision rows are the PR's then the base's, and the table keeps 10 rows
//!   ([`resolve_progress`]; docs/progress-docs.md).
//! - **Conflicts in the generated docs are regenerated** ("take
//!   either side and regenerate"): a doc of [`Project::generated`] takes the base's side, the
//!   rebase or merge finishes, and it is then regenerated by its own command on the stacked tree
//!   ([`crate::Hooks::regenerate`]) and committed on `s-<pr>` as "regenerated <doc> (stack)". The
//!   record names it ([`Entry::regenerated`]); the commit is in the rebased tip, so the gate checks
//!   it (`<command> --check`) and `land` pushes it with the PR.
//! - **Any other conflict is refused:** the rebase or merge is aborted and the files named. HEAD
//!   goes back to the top of the PRs stacked before it (`<remote>/<base>`, detached, when none),
//!   and only those are recorded, so a gate run next never tests the failing PR's unrebased branch
//!   ([`Stopped`]).
//! - **The issues a PR closes** come from its description (`Closes #n`), never by hand.
//! - **A PR with no work is refused** ([`crate::empty`]): stacked, it has no
//!   commits of its own, only claim commits, or an empty diff. The stack stops at it as at a
//!   conflict.

