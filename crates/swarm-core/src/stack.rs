// The generated docs' conflicts.

/// What [`resolve_conflicts`] does with a stop's conflicted files.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Conflicts<'a> {
    /// Generated docs: the base's side now, regenerated once the rebase or merge is done.
    pub regenerate: Vec<&'static Generated>,
    /// Other Markdown: a progress doc's header and revision rows ([`resolve_progress`]).
    pub progress: Vec<&'a str>,
}

/// Sort a stop's `conflicted` files into [`Conflicts`], or refuse, naming the files no rule
/// resolves: anything but Markdown, and `project`'s generated docs too when `regenerate` is off
/// (`land`'s merge of `main`, which no gate checks after).
pub fn plan_conflicts<'a>(project: &Project, conflicted: &'a [String], regenerate: bool) -> Result<Conflicts<'a>, String> {
    if conflicted.is_empty() {
        return Err("it stopped with no conflicted file".into());
    }
    let mut plan = Conflicts::default();
    let mut other = Vec::new();
    for f in conflicted {
        match project.generated(f) {
            Some(g) if regenerate => plan.regenerate.push(g),
            Some(_) => other.push(format!("{f} (generated: restack, and `stack` regenerates it)")),
            None if f.to_ascii_lowercase().ends_with(".md") => plan.progress.push(f),
            None => other.push(f.clone()),
        }
    }
    if !other.is_empty() {
        return Err(format!("conflicts outside the progress and generated docs, resolve by hand: {}", other.join(", ")));
    }
    Ok(plan)
}

/// Regenerates a generated doc in the worktree at a root: [`Hooks::regenerate`], or a test's fake.
pub type Regen<'a> = &'a dyn Fn(&Path, &Generated) -> Result<(), String>;

/// `cargo xtask <doc's command>` at `root`, run as this xtask's own exe, as the gate runs `ci`:
/// cargo never rebuilds the running xtask on Windows, and the gate's `--check` is the same code.
/// [`Hooks::regenerate`]'s default.
pub fn regenerate(root: &Path, doc: &Generated) -> Result<(), String> {
    let exe = std::env::current_exe().map_err(|e| format!("this xtask's path: {e}"))?;
    let mut c = Command::new(exe);
    c.current_dir(root).arg(doc.command);
    println!("stack: regenerating {} (cargo xtask {})", doc.path, doc.command);
    crate::process::output(c, None, REGEN, &format!("cargo xtask {}", doc.command)).map(|_| ()).map_err(|e| tail(&e, 20))
}

/// The last `n` lines of `text` (a build's error ends with what matters).
fn tail(text: &str, n: usize) -> String {
    let lines: Vec<&str> = text.lines().collect();
    lines.get(lines.len().saturating_sub(n)..).unwrap_or_default().join("\n")
}

/// `git <args> -- <paths>` at `root`.
fn git_on(root: &Path, args: &[&str], paths: &[&str]) -> Result<String, String> {
    git(root, &[args, &["--"], paths].concat(), None, &[])
}

/// Regenerate `docs` at `root` and commit what changed as "regenerated <docs> (stack)"; the docs
/// committed. On a failure the docs go back to HEAD's, so the tree is clean for the stop.
fn regenerate_docs(root: &Path, docs: &[&Generated], regen: Regen<'_>) -> Result<Vec<String>, String> {
    let paths: Vec<&str> = docs.iter().map(|d| d.path).collect();
    let made = docs.iter().try_for_each(|d| regen(root, d).map_err(|e| format!("regenerating {}: {e}", d.path)));
    let staged = made.and_then(|()| git_on(root, &["add"], &paths));
    if let Err(e) = staged {
        let restore = git_on(root, &["checkout", "--quiet", "HEAD"], &paths);
        return Err(match restore {
            Ok(_) => e,
            Err(r) => format!("{e} (and restoring them failed: {r})"),
        });
    }
    let changed: Vec<String> = git_on(root, &["diff", "--cached", "--name-only"], &paths)?.lines().map(str::to_owned).collect();
    if changed.is_empty() {
        // The base's side was already right for the stacked tree.
        return Ok(changed);
    }
    let message = format!("regenerated {} (stack)", changed.join(", "));
    git(root, &["commit", "--quiet", "-m", &message], None, &[])?;
    println!("stack: {message}");
    Ok(changed)
}

