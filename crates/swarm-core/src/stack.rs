/// The revision rows a progress doc keeps (docs/progress-docs.md rule 2).
pub const KEEP_ROWS: usize = 10;
/// The most stops one rebase may make for progress-doc conflicts (one per replayed commit).
const MAX_STOPS: usize = 200;
/// The most PRs in one stack.
const MAX_MRS: usize = 20;
/// The progress docs' header line starts so (docs/progress-docs.md rule 1).
const HEADER: &str = "> **Last reviewed:**";
/// Their revision table follows this heading.
const REVISIONS: &str = "## Revision history";
/// A fetch, a rebase, a merge or a push in a big repository: longer than git's usual deadline.
const SLOW: Duration = Duration::from_secs(300);
/// Regenerating a doc: its command builds a binary, from cold in a fresh target dir.
const REGEN: Duration = Duration::from_secs(1800);

/// The usage line, as [`crate::COMMANDS`] lists it.
pub const USAGE: &str = "cargo xtask stack <pr>… [--agent <instance>] [--remote <name>] [--base <branch>]";

/// The whole usage, for `project`.
fn usage(project: &Project) -> String {
    let docs: Vec<&str> = project.generated.iter().map(|g| g.path.rsplit('/').next().unwrap_or(g.path)).collect();
    format!(
        "usage: {USAGE}
  for each PR in order, in this worktree: `checkout -B s-<pr>` at its source branch and rebase it
  onto <remote>/<base> (default origin/main), or onto the PR before it (a branch with merge
  commits: its base merged in instead). Records each branch's pre-rebase tip for `cargo xtask
  land`. Resolves conflicts in the progress docs' headers and revision tables, and in the
  generated docs ({}: the base's side, then each is regenerated on the stacked tree and committed
  on s-<pr>); any other conflict aborts and names the files, and HEAD goes back to the top of the
  PRs stacked before it, which alone are recorded. A PR with no work stops it too. Takes the gate
  lock first (`cargo xtask lock`; --agent, default {}).",
        docs.join(", "),
        project.env_name("AGENT")
    )
}

