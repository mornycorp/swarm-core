/// Git in `dir` with time for a big repository (a fetch, a rebase, a merge, a push).
pub fn git_slow(dir: &Path, args: &[&str], env: &[(&str, &str)]) -> Result<String, String> {
    let mut c = Command::new("git");
    c.current_dir(dir).args(args).env("GIT_TERMINAL_PROMPT", "0");
    for (k, v) in env {
        c.env(k, v);
    }
    let what = format!("git {}", args.iter().copied().filter(|a| !a.starts_with("-c") && !a.contains('=')).take(3).collect::<Vec<_>>().join(" "));
    crate::process::output(c, None, SLOW, &what)
}

/// The stack's record for the worktree at `root`.
pub fn state_path(project: &Project, root: &Path) -> Result<PathBuf, String> {
    Ok(PathBuf::from(git(root, &["rev-parse", "--path-format=absolute", "--git-path", project.stack_state], None, &[])?.trim()))
}

/// The stack this worktree last made.
pub fn load(project: &Project, root: &Path) -> Result<Stack, String> {
    let path = state_path(project, root)?;
    let text =
        std::fs::read_to_string(&path).map_err(|e| format!("no stack in this worktree ({}: {e}): run `cargo xtask stack <pr>…` first", path.display()))?;
    let v: Value = serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
    Stack::from_json(&v).map_err(|e| format!("{}: {e}", path.display()))
}

/// The stack's record, if this worktree has one (none: `None`; one that can't be read: an error).
pub fn load_any(project: &Project, root: &Path) -> Result<Option<Stack>, String> {
    if !state_path(project, root)?.exists() {
        return Ok(None);
    }
    load(project, root).map(Some)
}

/// Record `stack` (none left: the record goes).
pub fn save(project: &Project, root: &Path, stack: &Stack) -> Result<(), String> {
    let path = state_path(project, root)?;
    if stack.entries.is_empty() {
        return match std::fs::remove_file(&path) {
            Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(format!("{}: {e}", path.display())),
            _ => Ok(()),
        };
    }
    let text = serde_json::to_string_pretty(&stack.to_json()).map_err(|e| e.to_string())?;
    std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))
}

/// Refuse a worktree mid-rebase or mid-merge, or with tracked changes: a stack starts from a
/// clean tree.
pub fn check_clean(root: &Path) -> Result<(), String> {
    // One git process for the three paths.
    let states = ["rebase-merge", "rebase-apply", "MERGE_HEAD"];
    let paths = git(root, &["rev-parse", "--path-format=absolute", "--git-path", states[0], "--git-path", states[1], "--git-path", states[2]], None, &[])?;
    for (dir, p) in states.iter().zip(paths.lines()) {
        if Path::new(p.trim()).exists() {
            return Err(format!("a rebase or merge is in progress in this worktree ({dir}): finish or abort it first"));
        }
    }
    let status = git(root, &["status", "--porcelain", "--untracked-files=no"], None, &[])?;
    if !status.trim().is_empty() {
        return Err(format!("this worktree has tracked changes: commit or drop them first\n{}", status.trim_end()));
    }
    Ok(())
}

pub fn rev(root: &Path, r: &str) -> Result<String, String> {
    Ok(git(root, &["rev-parse", "--verify", "--quiet", &format!("{r}^{{commit}}")], None, &[]).map_err(|_| format!("no commit `{r}`"))?.trim().to_owned())
}

/// Does `from..to` hold a merge commit?
fn has_merges(root: &Path, from: &str, to: &str) -> Result<bool, String> {
    Ok(git(root, &["rev-list", "--merges", "--count", &format!("{from}..{to}")], None, &[])?.trim() != "0")
}

/// Why [`build`] stopped.
#[derive(Debug)]
pub enum Stopped {
    /// Before the first PR: nothing was checked out, and the record is as it was.
    Early(String),
    /// At a PR: HEAD is back at the top of `stack`, the PRs stacked before it (`<remote>/<base>`,
    /// detached, when none), never on the failing PR's unrebased branch.
    At { stack: Stack, why: String },
}

/// Stack `mrs` in the worktree at `root`, fetching from `remote`, onto `<remote>/<base>`; `regen`
/// writes a generated doc that conflicted ([`Hooks::regenerate`]).
pub fn build(project: &Project, root: &Path, remote: &str, base: &str, mrs: &[StackMr], regen: Regen<'_>) -> Result<Stack, Stopped> {
    let main = base_tip(root, remote, base).map_err(Stopped::Early)?;
    let mut stack = Stack { remote: remote.to_owned(), base: base.to_owned(), entries: Vec::new() };
    for m in mrs {
        let (onto, below_old) = stack.entries.last().map_or((main.as_str(), None), |e| (e.new_tip.as_str(), Some(e.old_tip.as_str())));
        match stack_one(&Onto { project, root, remote, onto, below_old }, m, regen) {
            Ok(e) => stack.entries.push(e),
            Err(why) => {
                let why = format!("{why}\n{}", back_to_top(root, &stack, &main));
                return Err(Stopped::At { stack, why });
            }
        }
    }
    Ok(stack)
}

/// A clean worktree, and `<remote>/<base>` fetched: its commit.
fn base_tip(root: &Path, remote: &str, base: &str) -> Result<String, String> {
    check_clean(root)?;
    let tracking = format!("refs/remotes/{remote}/{base}");
    event::fetch(root, remote, &format!("refs/heads/{base}"), &tracking)?;
    rev(root, &tracking)
}

/// After a stop: check out the top of the PRs stacked so far (`s-<pr>`), or `main` detached when
/// none, so a gate run next tests what the record says. What HEAD is now, in a line.
fn back_to_top(root: &Path, stack: &Stack, main: &str) -> String {
    let (target, what) = match stack.entries.last() {
        Some(e) => (local_branch(e.mr), format!("{} ({}), the top of {}", local_branch(e.mr), short(&e.new_tip), mr_list(stack))),
        None => (main.to_owned(), format!("{}/{} ({}): nothing stacked", stack.remote, stack.base, short(main))),
    };
    let mut args = vec!["checkout", "--quiet"];
    if stack.entries.is_empty() {
        args.push("--detach");
    }
    args.extend([target.as_str(), "--"]);
    match git(root, &args, None, &[]) {
        Ok(_) => format!("stack: HEAD is {what}; only those are recorded"),
        Err(e) => format!("stack: HEAD could not go back to {what} ({e}): don't gate this tree"),
    }
}

/// `!1 #2`: a stack's PRs (`none`).
pub fn mr_list(stack: &Stack) -> String {
    let list: Vec<String> = stack.entries.iter().map(|e| format!("#{}", e.mr)).collect();
    if list.is_empty() { "none".to_owned() } else { list.join(" ") }
}

/// Where one PR is stacked: in `root`'s worktree, fetched from `remote`, onto `onto` (the base's
/// tip, or the rebased tip of the PR below, whose pre-rebase tip is `below_old`).
struct Onto<'a> {
    project: &'a Project,
    root: &'a Path,
    remote: &'a str,
    onto: &'a str,
    below_old: Option<&'a str>,
}

/// Stack PR `m` as `s-<pr>` on `at.onto`: rebased (from the old tip of the PR below, when it was
/// stacked on it), or with `onto` merged in when it carries merge commits. Refused when it then
/// holds no work.
fn stack_one(at: &Onto<'_>, m: &StackMr, regen: Regen<'_>) -> Result<Entry, String> {
    let Onto { project, root, remote, onto, below_old } = *at;
    let src = &m.source_branch;
    let tracking = format!("refs/remotes/{remote}/{src}");
    event::fetch(root, remote, &format!("refs/heads/{src}"), &tracking).map_err(|e| format!("#{}: fetching {src}: {e}", m.iid))?;
    let old_tip = rev(root, &tracking)?;
    git(root, &["checkout", "--quiet", "-B", &local_branch(m.iid), &old_tip], None, &[])?;
    // Stacked on the PR below: replay only this PR's own commits onto that PR's rebased tip.
    let upstream = match below_old {
        Some(b) if git(root, &["merge-base", "--is-ancestor", b, &old_tip], None, &[]).is_ok() => b,
        _ => onto,
    };
    let at_mr = |e: String| format!("#{} ({src}): {e}", m.iid);
    let merged_base = has_merges(root, upstream, &old_tip)?;
    let step = if merged_base { merge_with(project, root, onto, true) } else { rebase(project, root, onto, upstream) };
    let docs = step.map_err(at_mr)?;
    // On the stacked tree, in a commit of its own on top: the gate checks it, `land` pushes it.
    let regenerated = if docs.is_empty() { Vec::new() } else { regenerate_docs(root, &docs, regen).map_err(at_mr)? };
    let new_tip = rev(root, "HEAD")?;
    // A PR with no work (#320 merged with only its claim commit) is never
    // stacked.
    if let Some(why) = crate::empty::why(root, onto, &new_tip)? {
        return Err(at_mr(crate::empty::refusal(&why)));
    }
    let files: Vec<String> = git(root, &["diff", "--name-only", onto, &new_tip], None, &[])?.lines().map(str::to_owned).collect();
    Ok(Entry {
        mr: m.iid,
        source_branch: src.clone(),
        title: m.title.clone(),
        issues: m.issues.clone(),
        old_tip,
        new_tip,
        onto: onto.to_owned(),
        docs_only: docs_only(&files),
        merged_base,
        regenerated,
    })
}

/// No editor (the replayed messages are kept), and plain conflict markers whatever the
/// coordinator's config says.
const NO_EDITOR: [(&str, &str); 2] = [("GIT_EDITOR", "true"), ("GIT_SEQUENCE_EDITOR", "true")];
const STYLE: &str = "merge.conflictStyle=merge";

/// Resolve the conflicted files at `root` if [`plan_conflicts`] has a rule for each (`side` is the
/// PR's), and stage them: progress docs resolved, generated docs at the base's side. The generated
/// docs to regenerate once it is done; else why not.
fn resolve_conflicts(project: &Project, root: &Path, side: MrSide, regenerate: bool) -> Result<Vec<&'static Generated>, String> {
    let conflicted: Vec<String> = git(root, &["diff", "--name-only", "--diff-filter=U"], None, &[])?.lines().map(str::to_owned).collect();
    let plan = plan_conflicts(project, &conflicted, regenerate)?;
    // The base is `--ours` in a rebase and `--theirs` merging it into the PR's branch.
    let base_side = match side {
        MrSide::Theirs => "--ours",
        MrSide::Ours => "--theirs",
    };
    for g in &plan.regenerate {
        git(root, &["checkout", base_side, "--", g.path], None, &[])?;
        git(root, &["add", "--", g.path], None, &[])?;
        println!("stack: took the base's {} (regenerated once stacked)", g.path);
    }
    for f in plan.progress {
        let path = root.join(f);
        let text = std::fs::read_to_string(&path).map_err(|e| format!("{f}: {e}"))?;
        std::fs::write(&path, resolve_progress(f, &text, side)?).map_err(|e| format!("{f}: {e}"))?;
        git(root, &["add", "--", f], None, &[])?;
        println!("stack: resolved {f} (header and revision rows)");
    }
    Ok(plan.regenerate)
}

/// `git rebase --onto <onto> <upstream>` of HEAD, resolving the progress and generated docs'
/// conflicts at each stop; any other conflict aborts it, naming the files. The generated docs to
/// regenerate, each once.
fn rebase(project: &Project, root: &Path, onto: &str, upstream: &str) -> Result<Vec<&'static Generated>, String> {
    let mut docs: Vec<&'static Generated> = Vec::new();
    let mut result = git_slow(root, &["-c", STYLE, "rebase", "--quiet", "--onto", onto, upstream], &NO_EDITOR);
    for _ in 0..MAX_STOPS {
        let Err(e) = result else { return Ok(docs) };
        let more = resolve_conflicts(project, root, MrSide::Theirs, true).map_err(|why| abort(root, "rebase", format!("{why} ({e})")))?;
        for g in more {
            if !docs.contains(&g) {
                docs.push(g);
            }
        }
        result = git_slow(root, &["-c", STYLE, "rebase", "--continue"], &NO_EDITOR);
    }
    Err(abort(root, "rebase", format!("the rebase stopped more than {MAX_STOPS} times")))
}

/// Merge `base` into HEAD (a branch with merge commits, or one the server can't rebase),
/// resolving the progress docs' conflicts; any other conflict aborts it, naming the files. A
/// generated doc's too: this is `land`'s merge of `main`, which no gate checks after.
pub fn merge_in(project: &Project, root: &Path, base: &str) -> Result<(), String> {
    merge_with(project, root, base, false).map(|_| ())
}

/// [`merge_in`], with the generated docs' conflicts at the base's side when `regenerate`: the docs
/// to regenerate.
fn merge_with(project: &Project, root: &Path, base: &str, regenerate: bool) -> Result<Vec<&'static Generated>, String> {
    let Err(e) = git_slow(root, &["-c", STYLE, "merge", "--quiet", "--no-edit", base], &NO_EDITOR) else { return Ok(Vec::new()) };
    let docs = resolve_conflicts(project, root, MrSide::Ours, regenerate).map_err(|why| abort(root, "merge", format!("{why} ({e})")))?;
    git_slow(root, &["commit", "--quiet", "--no-edit"], &NO_EDITOR).map_err(|e| abort(root, "merge", e))?;
    Ok(docs)
}

/// Abort the rebase or merge in progress, and say why (and if the abort failed too).
fn abort(root: &Path, what: &str, why: String) -> String {
    match git(root, &[what, "--abort"], None, &[]) {
        Ok(_) => format!("{why} ({what} aborted)"),
        Err(e) => format!("{why} (and the abort failed: {e})"),
    }
}

/// `stack`'s options.
#[derive(Debug, PartialEq, Eq)]
struct Opts {
    mrs: Vec<u64>,
    agent: Option<String>,
    remote: String,
    base: String,
}

fn parse_args(project: &Project, args: &[&str]) -> Result<Opts, String> {
    let (mut mrs, mut agent, mut remote, mut base) = (Vec::new(), None, project.branches.remote.to_owned(), project.branches.main.to_owned());
    let mut it = args.iter().copied();
    while let Some(a) = it.next() {
        let mut value = || it.next().map(str::to_owned).ok_or_else(|| usage(project));
        match a {
            "--agent" => agent = Some(value()?),
            "--remote" => remote = value()?,
            "--base" => base = value()?,
            "-h" | "--help" => return Err(usage(project)),
            n if !n.starts_with('-') => {
                let m: u64 = n.trim_start_matches('#').parse().map_err(|_| format!("stack: `{n}` is not a PR number\n\n{}", usage(project)))?;
                if mrs.contains(&m) {
                    return Err(format!("stack: #{m} given twice"));
                }
                mrs.push(m);
            }
            other => return Err(format!("stack: unknown option `{other}`\n\n{}", usage(project))),
        }
    }
    if mrs.is_empty() || mrs.len() > MAX_MRS {
        return Err(format!("stack: name 1 to {MAX_MRS} PRs\n\n{}", usage(project)));
    }
    for name in [&remote, &base] {
        if !valid_branch(name) {
            return Err(format!("stack: `{name}` is not a remote or branch name"));
        }
    }
    Ok(Opts { mrs, agent, remote, base })
}

/// `cargo xtask stack <pr>…` ([`USAGE`]) for `project`.
pub fn run(project: &Project, hooks: &dyn Hooks, root: &Path, args: &[&str]) -> Result<(), String> {
    let Opts { mrs: iids, agent, remote, base } = parse_args(project, args)?;
    let agent = crate::lock::agent(project, agent, "stack")?;
    check_clean(root)?;
    let mut mrs = Vec::new();
    for m in &iids {
        mrs.push(parse_mr(project, &crate::github::pr(project, *m)?)?);
    }
    // A rebase is already a write to the worktree: the gate's lock first.
    crate::lock::take(project, root, &agent)?;
    let regen = |root: &Path, doc: &Generated| hooks.regenerate(root, doc);
    let stack = match build(project, root, &remote, &base, &mrs, &regen) {
        Ok(stack) => stack,
        Err(Stopped::Early(why)) => return Err(why),
        // Only the PRs stacked before the stop are recorded, and HEAD is their top: the error's
        // last line says so.
        Err(Stopped::At { stack, why }) => {
            save(project, root, &stack)?;
            report(&stack);
            return Err(format!("stack stopped: {why}"));
        }
    };
    save(project, root, &stack)?;
    report(&stack);
    let list: Vec<String> = stack.entries.iter().map(|e| e.mr.to_string()).collect();
    println!("stack: HEAD is the top of the stack; `cargo xtask gate --sub <sub> --note …`, then `cargo xtask land {} --sub <sub>`", list.join(" "));
    Ok(())
}

/// One line per stacked PR.
fn report(stack: &Stack) {
    for e in &stack.entries {
        let issues: Vec<String> = e.issues.iter().map(|n| format!("#{n}")).collect();
        let closes = if issues.is_empty() { "closes no issue".to_owned() } else { format!("closes {}", issues.join(" ")) };
        let kind = if e.docs_only { "docs only" } else { "code" };
        let how = if e.merged_base { "base merged in" } else { "rebased" };
        let regen = if e.regenerated.is_empty() { String::new() } else { format!("; regenerated {}", e.regenerated.join(", ")) };
        println!(
            "stack: #{} {} -> {}: {} -> {} ({how}{regen}; {kind}; {closes})",
            e.mr,
            e.source_branch,
            local_branch(e.mr),
            short(&e.old_tip),
            short(&e.new_tip)
        );
    }
}

/// Real git repositories for the tests of `stack` and `land`.
#[cfg(test)]
pub mod testgit {
    use std::io::Write;
    use std::path::Path;
    use std::process::{Command, Stdio};
    use std::sync::atomic::{AtomicU64, Ordering};

    pub use swarm_core_testkit::git::git as tgit;

    /// A bare repository at `dir`: an origin.
    pub fn bare(dir: &Path) {
        std::fs::create_dir_all(dir).unwrap();
        tgit(dir, &["init", "--bare", "--quiet", "-b", "main"]);
    }

    /// A clone of `origin` at `to` with the tests' identity in its config, checked out as
    /// committed whatever the machine's `core.autocrlf`: one git process.
    pub fn clone(origin: &Path, to: &Path) {
        let (from, into) = (origin.to_string_lossy(), to.to_string_lossy());
        let mut args = vec!["clone", "--quiet"];
        for c in ["core.autocrlf=false", "user.name=swarm-test", "user.email=swarm-test@example.invalid", "commit.gpgsign=false"] {
            args.extend(["-c", c]);
        }
        args.extend([&*from, &*into]);
        tgit(to.parent().unwrap(), &args);
    }

    /// Each commit's time: one minute after the one before, in any history of this process, so
    /// two commits are the same commit only when they are made the same in one history.
    static CLOCK: AtomicU64 = AtomicU64::new(1_700_000_000);

    /// A fixture's commits, written straight into a repository (a bare origin, say) by one `git
    /// fast-import`. A worker's clone that adds, commits and pushes each of them
    /// took three to five git processes a commit (a push starts more), each 0.1 to 3 s on a
    /// loaded Windows machine.
    #[derive(Default)]
    pub struct History {
        stream: String,
        marks: usize,
    }

    /// A branch name as fast-import takes it: `refs/…` as given, else a branch.
    fn full(name: &str) -> String {
        if name.starts_with("refs/") { name.to_owned() } else { format!("refs/heads/{name}") }
    }

    impl History {
        /// A commit on `branch` whose parents are `parents` (marks this history gave, or refs the
        /// repository has: a branch, or `refs/…`; none: a root commit) and whose tree is its
        /// first parent's with `files` written. Its mark, for a later commit's parents.
        pub fn commit(&mut self, branch: &str, parents: &[&str], files: &[(&str, &str)], message: &str) -> String {
            self.marks += 1;
            let mark = format!(":{}", self.marks);
            let when = CLOCK.fetch_add(60, Ordering::Relaxed);
            let data = |s: &str| format!("data {}\n{s}\n", s.len());
            let branch = full(branch);
            // A reset first, so a commit with no parents is a root even on a branch this history
            // already wrote.
            self.stream += &format!("reset {branch}\n\ncommit {branch}\nmark {mark}\n");
            self.stream += &format!("committer swarm-test <swarm-test@example.invalid> {when} +0000\n{}", data(message));
            for (i, p) in parents.iter().enumerate() {
                let parent = if p.starts_with(':') { (*p).to_owned() } else { format!("{}^0", full(p)) };
                self.stream += &format!("{} {parent}\n", if i == 0 { "from" } else { "merge" });
            }
            for (path, text) in files {
                self.stream += &format!("M 100644 inline {path}\n{}", data(text));
            }
            self.stream.push('\n');
            mark
        }

        /// Write the commits into `repo`, moving their branches. Each commit's id, in the order
        /// they were made.
        pub fn import(self, repo: &Path) -> Vec<String> {
            let marks = repo.with_extension("marks");
            let mut child = Command::new("git")
                .arg("-C")
                .arg(repo)
                .args(["fast-import", "--quiet", "--done", "--force"])
                .arg(format!("--export-marks={}", marks.display()))
                .stdin(Stdio::piped())
                .stdout(Stdio::null())
                .stderr(Stdio::piped())
                .spawn()
                .unwrap();
            child.stdin.take().unwrap().write_all(format!("{}done\n", self.stream).as_bytes()).unwrap();
            let out = child.wait_with_output().unwrap();
            assert!(out.status.success(), "git fast-import in {}: {}", repo.display(), String::from_utf8_lossy(&out.stderr));
            let text = std::fs::read_to_string(&marks).unwrap();
            let _ = std::fs::remove_file(&marks);
            ids_of_marks(&text, self.marks)
        }
    }

    /// The commit ids in an `--export-marks` file (`:<mark> <id>` lines), by mark from 1 to `n`.
    fn ids_of_marks(text: &str, n: usize) -> Vec<String> {
        let mut ids = vec![String::new(); n];
        for (mark, id) in text.lines().filter_map(|l| l.strip_prefix(':')?.split_once(' ')) {
            ids[mark.parse::<usize>().unwrap() - 1] = id.to_owned();
        }
        ids
    }

    /// One commit on `branch` of `repo`, as [`History::commit`]: a worker's push, or what merged
    /// to main. Its id.
    pub fn push_commit(repo: &Path, branch: &str, parents: &[&str], files: &[(&str, &str)], message: &str) -> String {
        let mut h = History::default();
        h.commit(branch, parents, files, message);
        h.import(repo).remove(0)
    }
}

